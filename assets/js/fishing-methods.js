/**
 * Every commonly-trained RS3 Fishing method — level requirement, XP per
 * catch, and (where the underlying mechanic supports it) a level-99
 * XP/hour figure — for the Fishing XP calculator (second skill in the
 * planned skill-by-skill calculator rollout; see agility-courses.js for
 * the first, and xp-table.js for the level<->XP curve the calculator
 * itself will need alongside both).
 *
 * Fishing has no "lap" the way Agility does — throughput instead comes
 * from a per-attempt success *chance* that rises with level, so
 * `xpPerHourAt99` here isn't hand-transcribed prose the way Agility's
 * `xpPerHour` was; it's computed from the wiki's own live chance-calculator
 * data (Module:Fishing_chance_calculator/data, backing
 * https://runescape.wiki/w/Calculator:Fishing/Chance), using the exact
 * formula that module itself uses:
 *
 *   rawChance   = floor(((99-level)*low + (level-1)*high) / 98)   -- 1-98 scale, "low" at level 1 rising to "high" at 99
 *   chance      = clamp(rawChance / 256, 0, 1)                    -- per game tick (0.6s)
 *   actionsPerHour = 3600 / (delayTicks * 0.6)                    -- delayTicks is 4 unless a fish overrides it (`delay` below)
 *   xpPerHour   = actionsPerHour * chance * xpPerCatch            -- at level 99, no gear/aura bonuses
 *
 * A few fish share one physical spot (Menaphos's bait spot, the Arc's rod/
 * net spots) — a miss on the first fish rolls into a chance at the next, so
 * `xpPerHourAt99` for those is that fish's own share of the shared spot's
 * total throughput, not a rate it could hit alone; `sharedSpot` on each
 * lists what else rolls there.
 *
 * Cross-checked against the wiki's own general Fishing article
 * (https://runescape.wiki/w/Fishing#Types_of_fish) the same way
 * agility-courses.js cross-checked the Agility article against per-course
 * pages and the 2026 rebalance pages — and the same thing happened here:
 * the shared article turned out to be stale for the three Barbarian
 * Fishing "leaping" fish specifically (it lists 60/82/92 xp for leaping
 * trout/salmon/sturgeon; the dedicated Barbarian Fishing page, and the
 * chance-calculator data, both agree on the lower and correct 50/70/80).
 * Checked both 2026 rebalance pages too
 * (https://runescape.wiki/w/2026_early-game_rebalance and
 * .../2026_mid-game_rebalance) — unlike Agility, Fishing XP values weren't
 * part of either rebalance; the only change was a catch-*chance* tweak
 * (shrimp/crayfish success at level 1 cut from 60% to 20%, already
 * reflected in the chance-calculator data used here).
 *
 * Deep Sea Fishing is a partial exception: its own dedicated page quotes
 * "around N experience an hour at level 99" for four of its methods
 * (magnetic minnow, both jellyfish, sailfish) that don't match this
 * formula — DSF layers on mechanics the base chance data doesn't model
 * (minnows catch 1-3 at once; jellyfish/sailfish spots come in several
 * sub-variants with different rates, plus streak/event XP bonuses). Those
 * four use the DSF page's own quoted figure instead of the formula's, each
 * noted as such.
 *
 * Deliberately excluded: the zero/one-xp junk byproducts of big-net
 * fishing (leather boots, seaweed, leather gloves, oyster, casket) — real
 * catches, but incidental, not a training target anyone picks a spot for.
 * Also excluded: giant crayfish (no chance data published — commented out
 * in the calculator's own source) and Croesus Front's fungal algae/
 * enriched fungal algae (absent from the calculator entirely) — both keep
 * their level/xp from the main article alone, with `xpPerHourAt99: null`.
 *
 * Not hand-maintained data in the usual sense — same caveat as
 * agility-courses.js: no Bucket table backs this, so re-derive by hand
 * (or re-run the formula above against a fresh copy of the calculator's
 * data module) if a new fish ships or the chance data changes.
 */

